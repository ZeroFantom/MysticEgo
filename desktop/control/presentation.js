export const languages=[['en','English'],['zh-CN','简体中文'],['ko','한국어'],['ru','Русский']];
export const fonts=[['modern','Современный'],['editorial','Редакционный'],['system','Системный'],['mono','Моноширинный']];
let language='en',font='modern';
export function t(source){const row=Object.hasOwn(catalog,source)?catalog[source]:undefined;return !row||language==='ru'?source:row[language==='en'?0:language==='zh-CN'?1:2]}
const fixed=[];
export function captureStatic(root){
 const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
 while(walker.nextNode()){
  const node=walker.currentNode,source=node.nodeValue.trim();
  if(source&&Object.hasOwn(catalog,source))fixed.push({node,source,raw:node.nodeValue});
 }
 for(const el of root.querySelectorAll('[aria-label],[placeholder],[title]'))for(const key of ['aria-label','placeholder','title']){
  const source=el.getAttribute(key);
  if(source&&Object.hasOwn(catalog,source))fixed.push({el,key,source});
 }
}
export function applyPresentation(value){
 language=languages.some(([id])=>id===value.language)?value.language:'en';
 font=fonts.some(([id])=>id===value.font)?value.font:'modern';
 document.documentElement.lang=language;document.documentElement.dataset.font=font;
 for(const item of fixed){
  if(item.node?.isConnected)item.node.nodeValue=item.raw.replace(item.source,t(item.source));
  if(item.el?.isConnected)item.el.setAttribute(item.key,t(item.source));
 }
}
