using MysticEgo.Capacity;
using MysticEgo.Distributed;
using Microsoft.AspNetCore.Http;
static void Check(bool ok,string message){if(!ok)throw new InvalidOperationException(message);}
var now=DateTimeOffset.UtcNow;
var pool=new ModelPool("physical","model","local",2,2,true);
var row=new CapacitySample("one","orchestra",now,90,40,1000000,500000,10,[pool,pool],5,1000);
var budget=new CapacityBudget("RUB",100,500,2000);
var assessment=CapacityAnalyzer.Analyze([row],budget,now);
Check(assessment.Nodes.Single().AvailableSlots==2,"Duplicate model alias counted twice");
Check(assessment.Nodes.Single().NetworkPercent==80,"Network utilization");
Check(assessment.AdditionalPools==1&&assessment.KnownMonthlyCost==1100&&assessment.ProjectedMonthlyCost==1600&&assessment.WithinBudget==true,"Cost including analyzer overhead");
Check(CapacityAnalyzer.Analyze([row],budget with{AnalyzerMonthlyCost=null},now).ProjectedMonthlyCost==null,"Missing cost treated as zero");
Check(CapacityAnalyzer.Analyze([row],budget with{MonthlyLimit=1200},now).WithinBudget==false,"Budget limit ignored");
var stale=CapacityAnalyzer.Analyze([row with{At=now.AddMinutes(-1)}],budget,now);
Check(stale.StaleNodes==1&&stale.AdditionalPools==null,"Stale demand included");
var unknown=CapacityAnalyzer.Analyze([row with{Pools=[pool with{Slots=0}],LinkMbps=null}],budget,now);
Check(unknown.Nodes.Single().AvailableSlots==null&&unknown.Nodes.Single().NetworkPercent==null,"Unknown capacity manufactured");
var registry=new CapacityRegistry();
Check(registry.Accept(row,now)&&!registry.Accept(row,now),"Duplicate sample accepted");
Check(!registry.Accept(row with{At=now.AddSeconds(30)},now),"Future sample accepted");
Check(!registry.Accept(row with{At=now.AddSeconds(1),CpuPercent=double.NaN},now),"Invalid metric accepted");
Check(registry.Read().Length==1,"Registry count");
const string origin="https://panel.example.test";
Check(BrowserSessionGateway.OriginAllowed(origin,origin,"panel.example.test"),"Same origin rejected");
Check(!BrowserSessionGateway.OriginAllowed(origin,"https://evil.example.test","panel.example.test"),"Cross-origin accepted");
Check(!BrowserSessionGateway.OriginAllowed(origin,origin,"evil.example.test"),"Host mismatch accepted");
Check(!BrowserSessionGateway.OriginAllowed(origin,null,"panel.example.test"),"Missing origin accepted");
var cookie=BrowserSessionGateway.Options();
Check(cookie.HttpOnly&&cookie.Secure&&cookie.SameSite==SameSiteMode.Strict&&cookie.Path=="/"&&cookie.Domain==null,"Unsafe cookie flags");
Console.WriteLine("Capacity, budget, telemetry and browser session contracts passed.");
