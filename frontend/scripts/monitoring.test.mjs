import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {chartGeometry,smoothEdges,gapPath} from '../packages/ui/src/pages/telemetryGeometry.ts';
const read=p=>readFileSync(new URL('../packages/ui/src/pages/'+p,import.meta.url),'utf8');
const diagnostics=read('Diagnostics.tsx'),network=read('Network.tsx'),agents=read('Agents.tsx'),css=read('monitoring.css');
assert(diagnostics.includes('chartGeometry(points,start,end,top,width,height)')&&diagnostics.includes('smoothEdges(segment)'));
assert(diagnostics.includes('chart-gap-bridge')&&diagnostics.includes('Нет данных · условный переход')&&diagnostics.includes('key={newestEdge.to.at}'));
assert(css.includes('chart-edge-reveal')&&css.includes('stroke-dasharray:5 4'));
const epoch=Date.parse('2026-01-01T00:00:00Z');
const sample=(seconds,value)=>({at:new Date(epoch+seconds*1000).toISOString(),value});
const data=[sample(0,0),sample(5,20),sample(10,null),sample(15,80),sample(20,70),sample(45,50),sample(50,NaN),sample(55,10)];
const geometry=chartGeometry(data,epoch,epoch+60000,100,420,112);
assert.deepEqual(geometry.segments.map(s=>s.length),[2,2,1,1]);
assert.deepEqual(geometry.gaps.map(g=>[(g.from.at-epoch)/1000,(g.to.at-epoch)/1000]),[[5,15],[20,45],[45,55]]);
assert.equal(geometry.segments[0][1].x,35);
assert.match(gapPath(geometry.gaps[0]),/^M .* C /);
assert.deepEqual(chartGeometry([sample(0,null),sample(5,-1)],epoch,epoch+60000,100,420,112),{segments:[],gaps:[]});
const duplicates=chartGeometry([sample(5,10),sample(0,0),sample(5,20)],epoch,epoch+60000,100,420,112);
assert.equal(duplicates.segments[0].length,2);
const points=[{x:0,y:10,at:0},{x:5,y:90,at:5},{x:15,y:12,at:15},{x:20,y:13,at:20},{x:25,y:80,at:25}];
const edges=smoothEdges(points);
assert.equal(edges.length,points.length-1);
for(const edge of edges){
  const [x1,y1,x2,y2,x,y]=edge.command.slice(2).split(' ').map(Number);
  assert([x1,y1,x2,y2,x,y].every(Number.isFinite));
  assert(x1>=edge.from.x&&x2>=x1&&x2<=edge.to.x);
  assert(y1>=Math.min(edge.from.y,edge.to.y)&&y1<=Math.max(edge.from.y,edge.to.y));
  assert(y2>=Math.min(edge.from.y,edge.to.y)&&y2<=Math.max(edge.from.y,edge.to.y));
  assert.equal(x,edge.to.x);assert.equal(y,edge.to.y);
}
assert.equal(smoothEdges([points[0]]).length,0);
assert(diagnostics.includes('Date.parse(s.at)>=start')&&diagnostics.includes('data-stale={stale}'));
const graph=readFileSync(new URL('../packages/ui/src/components/ControlGraph.tsx',import.meta.url),'utf8');
assert(network.includes('row.node.enabled&&')&&graph.includes('data-node-state={n.state}'));
assert(network.includes("topology.value?tile.count:topology.loading?'…':'—'"));
assert(network.includes('visited.has(child.node.id)')&&network.includes('item.node.id!==root'));
assert(graph.includes("transform:'scale('+zoom/100+')'")&&graph.includes('onPointerMove={move}')&&graph.includes('onKeyDown={e=>key(e,n)}'));
assert(network.includes('min={50} max={200}')&&network.includes('value={name??selected.node.name}'));
assert(agents.includes('!filtered.length')&&agents.includes('a.host??'));
assert(css.includes('prefers-reduced-motion:reduce')&&css.includes('data-ui-motion=off'));
console.log('Monitoring source contracts: timestamps, gaps, state, zoom, search and motion');
